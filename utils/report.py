from datetime import datetime


def generate_report(
    df,
    business_report="",
    recommendations="",
    forecast_summary=""
):
    """
    Generate a complete DecisionIQ Business Report.
    """

    rows, cols = df.shape

    numeric_cols = df.select_dtypes(include="number").columns.tolist()
    categorical_cols = df.select_dtypes(exclude="number").columns.tolist()

    missing = int(df.isnull().sum().sum())

    report = f"""
# 📄 DecisionIQ AI Business Report

Generated on: {datetime.now().strftime("%d-%b-%Y %I:%M %p")}

---

# Dataset Overview

- Total Rows : {rows:,}
- Total Columns : {cols}
- Numeric Columns : {len(numeric_cols)}
- Categorical Columns : {len(categorical_cols)}
- Missing Values : {missing}

Columns:

{', '.join(df.columns)}

---

# Business Report

{business_report}

---

# Forecast Summary

{forecast_summary if forecast_summary else "Forecast not generated."}

---

# Strategic Recommendations

{recommendations}

---

# Report Generated By

DecisionIQ

AI Powered Business Intelligence Platform

Developed using:

- Python
- Streamlit
- Pandas
- Plotly
- Prophet
- Groq LLM

"""

    return report